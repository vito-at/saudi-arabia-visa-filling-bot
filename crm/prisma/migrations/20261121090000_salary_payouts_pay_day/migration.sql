-- Выплаты (авансы) менеджерам с днём выплаты 20-го, внесённые за октябрь после 20.10, относятся к их ноябрьской зарплате
-- (период 21.10–20.11): октябрь 21.09–20.10 им выдали 20.10, ещё до начала учёта в CRM. Переносим в ноябрь.
UPDATE "SalaryPayout" p SET "month" = DATE '2026-11-01'
FROM "User" u
WHERE p."userId" = u."id" AND u."payDay" = 20 AND p."month" = DATE '2026-10-01' AND p."paidAt" >= TIMESTAMP '2026-10-20 19:00:00';
